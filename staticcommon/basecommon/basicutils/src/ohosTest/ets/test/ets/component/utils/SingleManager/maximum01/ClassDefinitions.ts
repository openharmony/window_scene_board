/* 测试获取指定用例，通过抛异常做校验，以免代码写的太长 */
function registerOneClass<T extends SingleBase>(manager: SingleManager, className: SingleBaseType<T>,
  dftSingle: T): void {
  let start = systemDateTime.getUptime(systemDateTime.TimeType.STARTUP, false);
  manager.register(className, dftSingle);
  let end = systemDateTime.getUptime(systemDateTime.TimeType.STARTUP, false);
  /* 不允许超过1ms */
  if ((end - start) > 1) {
    throw new Error(`register class to slow ${end - start}`);
  }
}

