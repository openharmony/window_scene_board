/* 测试获取指定用例，通过抛异常做校验，以免代码写的太长 */
function checkOneCase<T extends SingleBase>(manager: SingleManager, className: SingleBaseType<T>) : void {
  let start = systemDateTime.getUptime(systemDateTime.TimeType.STARTUP, false);
  let instance = manager.get(className);
  let end = systemDateTime.getUptime(systemDateTime.TimeType.STARTUP, false);
  if (!instance) {
    throw new Error(`instance is not exist`);
  }
  /* 不允许超过1ms */
  if ((end - start) > 1) {
    throw new Error(`get instance to slow ${end - start}`);
  }
}

